    private void notHlistasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_notHlistasActionPerformed
        // TODO add your handling code here:
        L_leer1 = notHlistas.getText().toUpperCase().trim();
        int validar = 0;

        switch (tipoLista) {
            case 1 -> {
                if (listaEn.esNuevo(L_leer1) == false) {
                    validar = 1;
                }
            }
            case 2 -> {
                if (listaDob.esNuevo(L_leer1) == false) {
                    validar = 1;
                }

            }
            case 3 -> {
                if (listaCir.esNuevo(L_leer1) == false) {
                    validar = 1;
                }

            }
        }

            notHlistas.setEnabled(false);
            switch (tiLiFu) {
                case 1 -> {
                    if (validar == 0) {
                    notHlistas.setEnabled(false);
                    hide1Listas.setVisible(true);
                    hideTlistas1.setVisible(true);} else {

            TxtListas.append(" * La tarea ya existe.\n\n");
            TxtListas.append("   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -\n\n");
            notHlistas.setText("");
            ListasRead.setVisible(false);
            jButton15.setEnabled(true);
            jButton16.setEnabled(true);
            RbDoble.setEnabled(true);
            RbSimple.setEnabled(true);
            RbCircular.setEnabled(true);
            notHlistas.setEnabled(true);

        }
                }
                case 2 -> {
                    switch (tipoLista) {
                        case 1 -> {
                            listaEn.eliminar(L_leer1, TxtListas);
                            RbDoble.setEnabled(true);
                            RbCircular.setEnabled(true);
                        }
                        case 2 -> {
                            listaDob.eliminar(L_leer1, TxtListas);
                            RbSimple.setEnabled(true);
                            RbCircular.setEnabled(true);
                        }
                        case 3 -> {
                            RbDoble.setEnabled(true);
                            RbSimple.setEnabled(true);
                            listaCir.eliminar(L_leer1, TxtListas);
                        }

                    }
                    TxtListas.append("   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -\n\n");
                    ListasRead.setVisible(false);
                    notHlistas.setEnabled(true);
                    notHlistas.setText("");
                    jButton14.setEnabled(true);
                    jButton16.setEnabled(true);
                    tiLiFu = 0;
                }
                case 3 -> {
                    switch (tipoLista) {
                        case 1 -> {
                            listaEn.buscar(L_leer1, TxtListas);
                            RbDoble.setEnabled(true);
                            RbCircular.setEnabled(true);
                        }
                        case 2 -> {
                            listaDob.buscar(L_leer1, TxtListas);
                            RbSimple.setEnabled(true);
                            RbCircular.setEnabled(true);
                        }
                        case 3 -> {
                            RbSimple.setEnabled(true);
                            RbDoble.setEnabled(true);
                            boolean esPosicion = L_leer1.matches("\\d+");
                            listaCir.buscar(L_leer1, esPosicion, TxtListas);
                        }
                    }
                    TxtListas.append("   - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -\n\n");
                    ListasRead.setVisible(false);
                    notHlistas.setEnabled(true);
                    notHlistas.setText("");
                    jButton14.setEnabled(true);
                    jButton15.setEnabled(true);

                }

            }
        
    }//GEN-LAST:event_notHlistasActionPerformed

